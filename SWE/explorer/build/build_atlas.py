# -*- coding: utf-8 -*-
"""PHASE 5 (atlas layer) of the SWE corpus explorer build.

Consumes the consolidated geography element_src/atlas.json (the WS2 deliverable: named islands with
deterministic precomputed coordinates + hulls, routes, and the bridge-flow projection) together with
the built element set, VALIDATES it hard, and emits data/atlas.json + data/atlas.js (window.SWE.atlas).

Audits (printed, fail loud):
  (a) PLACEMENT   - every design+architecture element sits in exactly one island; none unplaced/double.
  (b) COORDINATES - every island has cx/cy/r + a hull; every member has x/y in [0,1].
  (c) REFERENTIAL - every route/neighbour references a real island; bridge-flow anchors are real arch ids.
"""
import json, os, io, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'element_src')


def run(DATA):
    load = lambda f: json.load(open(os.path.join(SRC, f), encoding='utf-8'))
    design = load('design.json')['elements']
    arch = load('architecture.json')['elements']
    atlas = load('atlas.json')
    all_ids = {e['id'] for e in design} | {e['id'] for e in arch}
    arch_ids = {e['id'] for e in arch}

    islands = atlas['islands']
    island_ids = {i['id'] for i in islands}

    # ---- audit (a) PLACEMENT ----
    placed = {}
    dup = []
    for isl in islands:
        for m in isl['members']:
            if m['id'] in placed:
                dup.append(m['id'])
            placed[m['id']] = isl['id']
    unplaced = sorted(all_ids - set(placed))
    ghost = sorted(set(placed) - all_ids)
    print('PHASE 5 (atlas): %d islands, %d elements placed, %d routes, %d bridge-flow anchors.'
          % (len(islands), len(placed), len(atlas.get('routes', [])), len(atlas.get('bridgeFlow', {}).get('anchors', []))))
    problems = []
    if unplaced:
        problems.append('%d elements unplaced (e.g. %s)' % (len(unplaced), unplaced[:8]))
    if dup:
        problems.append('%d elements in >1 island (e.g. %s)' % (len(dup), dup[:8]))
    if ghost:
        problems.append('%d placed ids are not real elements (e.g. %s)' % (len(ghost), ghost[:8]))

    # ---- audit (b) COORDINATES ----
    fams = {f['id'] for f in atlas['meta']['families']}
    for isl in islands:
        for key in ('cx', 'cy', 'r', 'name', 'family'):
            if key not in isl or isl[key] in (None, ''):
                problems.append('island %s missing %s' % (isl['id'], key)); break
        if isl.get('family') not in fams:
            problems.append('island %s has unknown family %r' % (isl['id'], isl.get('family')))
        if not isl.get('hull') or len(isl['hull']) < 3:
            problems.append('island %s hull degenerate' % isl['id'])
        for m in isl['members']:
            x, y = m.get('x'), m.get('y')
            if not (isinstance(x, (int, float)) and isinstance(y, (int, float)) and -0.05 <= x <= 1.05 and -0.05 <= y <= 1.05):
                problems.append('island %s member %s bad coords' % (isl['id'], m['id'])); break

    # ---- audit (c) REFERENTIAL ----
    for r in atlas.get('routes', []):
        if r['from'] not in island_ids or r['to'] not in island_ids:
            problems.append('route references missing island: %s' % r); break
    for isl in islands:
        for nb in isl.get('neighbours', []):
            if nb['island'] not in island_ids:
                problems.append('island %s neighbour %s missing' % (isl['id'], nb['island'])); break
    for a in atlas.get('bridgeFlow', {}).get('anchors', []):
        if a['id'] not in arch_ids:
            problems.append('bridge-flow anchor %s is not an architecture element' % a['id']); break

    if problems:
        raise SystemExit('FATAL atlas validation: ' + '; '.join(problems[:8]))
    print('  placement: every element in exactly one island (%d/%d).' % (len(placed), len(all_ids)))
    print('  coordinates: all islands have cx/cy/r/hull; all members have x/y.')
    print('  referential: routes, neighbours, and bridge-flow anchors all resolve.')

    os.makedirs(DATA, exist_ok=True)
    with open(os.path.join(DATA, 'atlas.json'), 'w', encoding='utf-8') as f:
        json.dump(atlas, f, ensure_ascii=False, indent=1)
    js = ('// GENERATED by build/build_atlas.py - atlas layer (islands + geography over the element graph).\n'
          'window.SWE = window.SWE || {};\nSWE.atlas = ' + json.dumps(atlas, ensure_ascii=False) + ';\n')
    open(os.path.join(DATA, 'atlas.js'), 'w', encoding='utf-8').write(js)
    sizes = sorted((i['size'] for i in islands), reverse=True)
    print('  emitted data/atlas.json + data/atlas.js (%d islands; sizes %s%s).'
          % (len(islands), sizes[:8], ' …' if len(sizes) > 8 else ''))
    return atlas


if __name__ == '__main__':
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')
    run(os.path.normpath(os.path.join(HERE, '..', 'data')))
