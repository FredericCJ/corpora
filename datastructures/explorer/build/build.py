#!/usr/bin/env python3
# build/build.py — PHASE 4: merge -> validate -> emit. The only script that writes data/.
# Fail-loud validation (parse-don't-validate at the build boundary): unknown edge endpoints,
# duplicate ids, out-of-vocabulary kinds and dangling cycle tags abort the build.
#
# Emits (all four, kept in sync — the .json twins are inspectable phase artifacts, the .js
# twins are what the file://-opened page loads via classic <script>, since fetch() of JSON is
# blocked on file://):
#   data/corpus.js  / corpus.json      facts    (DS.corpus:  families + nodes)
#   data/relations.js / relations.json inference (DS.relations: kinds + edges + cycles + model)
#   data/corpus_report.md              build census (counts, verification, flags)

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from nodes import NODES                       # noqa: E402
from edges import EDGES, CYCLES               # noqa: E402

OUT = os.path.normpath(os.path.join(HERE, "..", "data"))

# ── Facts about grouping (families) and the relation vocabulary ──────────────────────────
FAMILIES = {
    "linear":   "Linear & sequence",
    "assoc":    "Sets, maps & associative",
    "hash":     "Hashing",
    "approx":   "Probabilistic / approximate",
    "tree":     "Trees & search trees",
    "trie":     "Digital trees & text",
    "heap":     "Heaps & priority queues",
    "spatial":  "Spatial & range",
    "advanced": "Graph, systems & advanced",
}
FAMILY_ORDER = ["linear", "assoc", "hash", "approx", "tree", "trie", "heap", "spatial", "advanced"]

# root -> modern relation vocabulary (topology §3), fixed order for stable legends.
KINDS = ["refines", "specializes", "generalizes", "encodes", "hybridizes", "influences"]

SRC = ["report:topology", "derived", "editorial"]


def fail(msg):
    print("BUILD FAILED:", msg, file=sys.stderr)
    sys.exit(1)


def validate():
    ids = [n["id"] for n in NODES]
    seen = set()
    for i in ids:
        if i in seen:
            fail(f"duplicate node id: {i}")
        seen.add(i)
    for n in NODES:
        if n["family"] not in FAMILIES:
            fail(f"node {n['id']} has unknown family {n['family']}")
        if n["tier"] not in ("root", "backfill", "modern"):
            fail(f"node {n['id']} has unknown tier {n['tier']}")
        if n["verification"] not in ("verified", "flagged"):
            fail(f"node {n['id']} has unknown verification {n['verification']}")
    for e in EDGES:
        if e["s"] not in seen:
            fail(f"edge source not a node: {e['s']} -> {e['t']}")
        if e["t"] not in seen:
            fail(f"edge target not a node: {e['s']} -> {e['t']}")
        if e["kind"] not in KINDS:
            fail(f"edge {e['s']}->{e['t']} has unknown kind {e['kind']}")
        if e["src"] not in SRC:
            fail(f"edge {e['s']}->{e['t']} has unknown src {e['src']}")
        if e["cycle"] and e["cycle"] not in CYCLES:
            fail(f"edge {e['s']}->{e['t']} tags unknown cycle {e['cycle']}")
    # every node participates in at least one edge (the graph draws only connected nodes)
    touched = set()
    for e in EDGES:
        touched.add(e["s"]); touched.add(e["t"])
    orphans = [i for i in ids if i not in touched]
    if orphans:
        fail(f"orphan nodes (no edge): {orphans}")


def census():
    lines = []
    lines.append("# corpus_report.md — build census (generated by build/build.py)\n")
    lines.append(f"- **Nodes:** {len(NODES)}  ·  **Edges:** {len(EDGES)}  ·  "
                 f"**Families:** {len(FAMILIES)}  ·  **Cycles:** {len(CYCLES)}\n")
    # tiers
    for tier in ("root", "backfill", "modern"):
        c = sum(1 for n in NODES if n["tier"] == tier)
        lines.append(f"- tier `{tier}`: {c}")
    lines.append("")
    # verification
    ver = sum(1 for n in NODES if n["verification"] == "verified")
    fla = sum(1 for n in NODES if n["verification"] == "flagged")
    lines.append(f"- verification: **{ver} verified**, **{fla} flagged**\n")
    # per-family counts
    lines.append("## Nodes per family\n")
    for f in FAMILY_ORDER:
        c = sum(1 for n in NODES if n["family"] == f)
        lines.append(f"- {FAMILIES[f]} (`{f}`): {c}")
    lines.append("")
    # edge provenance
    lines.append("## Edge provenance\n")
    for s in SRC:
        c = sum(1 for e in EDGES if e["src"] == s)
        lines.append(f"- `{s}`: {c}")
    lines.append("")
    # flagged nodes (honesty ledger)
    lines.append("## Flagged nodes (honestly marked, not dropped)\n")
    for n in NODES:
        if n["verification"] == "flagged":
            lines.append(f"- **{n['name']}** — {', '.join(n['flags']) or 'flagged'}")
    lines.append("")
    return "\n".join(lines)


def emit(path_base, namespace_key, obj):
    js_path = os.path.join(OUT, path_base + ".js")
    json_path = os.path.join(OUT, path_base + ".json")
    pretty = json.dumps(obj, ensure_ascii=False, indent=1)
    compact = json.dumps(obj, ensure_ascii=False)
    with open(json_path, "w", encoding="utf-8") as f:
        f.write(pretty + "\n")
    with open(js_path, "w", encoding="utf-8") as f:
        f.write("// GENERATED by build/build.py — do not hand-edit. Loaded via classic <script> "
                "so the page opens from file://.\n")
        f.write("window.DS = window.DS || {};\n")
        f.write(f"DS.{namespace_key} = {compact};\n")


def main():
    validate()
    os.makedirs(OUT, exist_ok=True)

    corpus = {
        "families": FAMILIES,
        "familyOrder": FAMILY_ORDER,
        "sources": {
            "audit": "Audit of ChatGPT's Foundational Source Answers for 17 Data Structures",
            "topology": "Topology of Data Structures: A Modern-Anchored, Bottom-Up Lineage Graph",
        },
        "nodes": NODES,
    }
    relations = {
        "kinds": KINDS,
        "edges": EDGES,
        "cycles": CYCLES,
        "model": {
            "label": "Lineage graph",
            "semantic": "Typed, directed, cyclic-capable relations between data structures "
                        "(root → modern).",
            "question": "What does this structure descend from, what descends from it, and how?",
            "computed": "Node set = every structure with >=1 edge; family bands are shelf-packed "
                        "to fit one viewport; within a band, nodes sort by (tier, year). Hover "
                        "traces the cycle-safe ancestor+descendant closure; every edge carries "
                        "kind + provenance + a one-line basis.",
        },
    }

    emit("corpus", "corpus", corpus)
    emit("relations", "relations", relations)
    with open(os.path.join(OUT, "corpus_report.md"), "w", encoding="utf-8") as f:
        f.write(census())

    print(f"OK  {len(NODES)} nodes, {len(EDGES)} edges, {len(FAMILIES)} families, "
          f"{len(CYCLES)} cycles -> {OUT}")


if __name__ == "__main__":
    main()
